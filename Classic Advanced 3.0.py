# --- Helper Functions (Copied from Training Script) ---
def compute_rsi(data, window=14):
    delta = data.diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=window).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=window).mean()
    rs = gain / loss
    return 100 - (100 / (1 + rs))

def compute_macd(data, short_window=12, long_window=26, signal_window=9):
    short_ema = data.ewm(span=short_window, adjust=False).mean()
    long_ema = data.ewm(span=long_window, adjust=False).mean()
    macd = short_ema - long_ema
    signal_line = macd.ewm(span=signal_window, adjust=False).mean()
    return macd, signal_line

def compute_bollinger_bands(data, window=20, num_std=2):
    rolling_mean = data.rolling(window=window).mean()
    rolling_std = data.rolling(window=window).std()
    upper_band = rolling_mean + (rolling_std * num_std)
    lower_band = rolling_mean - (rolling_std * num_std)
    return upper_band, lower_band

def compute_atr(high, low, close, window=14):
    high_low = high - low
    high_close = np.abs(high - close.shift())
    low_close = np.abs(low - close.shift())
    ranges = pd.concat([high_low, high_close, low_close], axis=1)
    true_range = ranges.max(axis=1)
    return true_range.rolling(window=window).mean()

def Hamdi(symbol):
    print(f"\nAnalyzing {symbol}...")
    
    # Configuration matching training
    WINDOW_SIZE = 48
    
    # Fetch data - Get enough history for indicators (200 days is safe for EMA 200)
    # We need a significant amount of data to stabilize the indicators and the scaler
    end_date = datetime.now()
    start_date = end_date - timedelta(days=200) 
    
    try:
        # Fetch 1h interval data
        # suppress yfinance progress bar
        df = yf.download(symbol, start=start_date, end=end_date, interval='1h', auto_adjust=True, progress=False)
        
        # Make sure we have enough data
        if len(df) < 300:
            print(f"Not enough data fetching for {symbol}. Got {len(df)} rows. Need at least 300 for stable indicators.")
            return

        # Ensure correct column accessing for MultiIndex if necessary
        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)
            
        current_price = float(df['Close'].iloc[-1])
            
        # --- Feature Engineering (Exactly as in Training) ---
        
        # Calculate Indicators
        df['RSI'] = compute_rsi(df['Close'])
        macd, signal_line = compute_macd(df['Close'])
        upper_bb, lower_bb = compute_bollinger_bands(df['Close'])
        atr = compute_atr(df['High'], df['Low'], df['Close'])
        sma_50 = df['Close'].rolling(window=50).mean()
        ema_200 = df['Close'].ewm(span=200, adjust=False).mean()

        # Create Stationary Features
        # 1. Log Returns
        df['Log_Return'] = np.log(df['Close'] / df['Close'].shift(1))

        # 2. Volume Change
        # Add epsilon to avoid log(0)
        df['Log_Volume_Change'] = np.log((df['Volume'] + 1) / (df['Volume'].shift(1) + 1))

        # 3. RSI Scaled
        df['RSI_Scaled'] = df['RSI'] / 100.0

        # 4. MACD Normalization
        df['MACD_Norm'] = macd / df['Close']
        df['Signal_Norm'] = signal_line / df['Close']

        # 5. Bollinger Band Features
        df['BB_Width'] = (upper_bb - lower_bb) / df['Close']
        df['BB_Position'] = (df['Close'] - lower_bb) / (upper_bb - lower_bb)

        # 6. Moving Average Distances
        df['SMA_50_Dist'] = (df['Close'] - sma_50) / sma_50
        df['EMA_200_Dist'] = (df['Close'] - ema_200) / ema_200

        # 7. ATR Percentage
        df['ATR_Pct'] = atr / df['Close']

        # 8. Cyclic Time Features
        df['Hour'] = df.index.hour
        df['DayOfWeek'] = df.index.dayofweek
        df['Hour_Sin'] = np.sin(2 * np.pi * df['Hour'] / 24)
        df['Hour_Cos'] = np.cos(2 * np.pi * df['Hour'] / 24)
        df['Day_Sin'] = np.sin(2 * np.pi * df['DayOfWeek'] / 7)
        df['Day_Cos'] = np.cos(2 * np.pi * df['DayOfWeek'] / 7)

        # Drop NaN values generated by indicators
        # This aligns the data start with valid calculable features
        df.dropna(inplace=True)
        
        # Select Features (Order MUST match training)
        features = [
            'Log_Return', 'Log_Volume_Change', 'RSI_Scaled', 
            'MACD_Norm', 'Signal_Norm', 
            'BB_Width', 'BB_Position', 
            'SMA_50_Dist', 'EMA_200_Dist', 'ATR_Pct',
            'Hour_Sin', 'Hour_Cos', 'Day_Sin', 'Day_Cos'
        ]
        
        # Prepare Data for Model
        data = df[features].values
        
        # Scale Data
        # We fit the scaler on the fetched historical data. 
        # Since we fetched ~200 days, this provides a good distribution for the scaler 
        # to normalize the current window effectively.
        scaler = RobustScaler()
        scaled_data = scaler.fit_transform(data)
        
        # We need the last WINDOW_SIZE data points for prediction
        if len(scaled_data) < WINDOW_SIZE:
            print(f"Not enough data after processing. Need {WINDOW_SIZE}, got {len(scaled_data)}")
            return
            
        # Reshape for model (1, WINDOW_SIZE, n_features)
        # Take the very last 48 hours
        X_input = scaled_data[-WINDOW_SIZE:].reshape(1, WINDOW_SIZE, len(features))
        
        # Load Model
        model_path = '/Users/ardaunal/Desktop/Hamdi/Hamdi_BTCST_Advanced_3.0.keras'
        
        if not os.path.exists(model_path):
             print(f"Error: Model not found at {model_path}")
             return

        model = load_model(model_path)
        
        # Predict
        prediction = model.predict(X_input, verbose=0)[0][0]
        
        # Interpret
        decision = "Increase" if prediction > 0.5 else "Decrease"
        confidence = prediction if prediction > 0.5 else (1 - prediction)
        
        # Output
        print(f"\n{symbol}: {current_price:,.2f} $")
        
        if decision == "Decrease":
            print(f"{symbol}: \033[91m{decision} (Confidence: {confidence:.2%}) ▼\033[0m\n")
        else:
            print(f"{symbol}: \033[92m{decision} (Confidence: {confidence:.2%}) ▲\033[0m\n")

    except Exception as e:
        print(f"An error occurred: {e}")
        # Optional: Print traceback for debugging
        # import traceback
        # traceback.print_exc()

